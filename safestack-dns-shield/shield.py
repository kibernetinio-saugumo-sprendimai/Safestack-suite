"""Generate a hosts blocklist from one-domain-per-line input."""
import argparse
import re
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from safestack_common import atomic_write, read_regular

DOMAIN = re.compile(
    r"(?=.{1,253}\Z)(?:[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?\.)+[a-z]{2,63}\Z",
    re.I
)


def generate(source, output):
    raw_content = read_regular(source).decode('utf-8', errors='strict')
    domains = []
    for line in raw_content.splitlines():
        line = line.strip().lower()
        if line and not line.startswith('#') and DOMAIN.fullmatch(line):
            domains.append(line)
    unique = sorted(set(domains))
    data = '# Generated by SafeStack DNS Shield\n' + ''.join(f'0.0.0.0 {d}\n' for d in unique)
    atomic_write(output, data.encode('utf-8'), 0o644)
    return len(unique)


if __name__ == '__main__':
    p = argparse.ArgumentParser(description="SafeStack DNS Shield - Hosts blocklist generator")
    p.add_argument('source', help="Input domain list (one per line)")
    p.add_argument('output', help="Output hosts blocklist file")
    x = p.parse_args()
    count = generate(x.source, x.output)
    print(f'Wrote {count} domains')

